function SidebarIcon({ size = 18 }: { size?: number }) {
  return <PanelIcon size={size} />
}

export const inject = ['slots', 'locale', 'inputTriggers']

export function apply(ctx: any): void {
  ctx.effect(() => ctx.locale.register(NS, { zh, en }), 'local-docs: dictionaries')
  const t = ctx.locale.bind(NS)
  const Panel = (props: Record<string, unknown>) => <LocalDocsApp {...props} t={t} />

  ctx.slots.inject('main', () =>
    ctx.slots.register({ name: 'main', key: PANEL_ID, locale: NS }, Panel),
  )
  const promptSource = createPromptMentionSource(t)
  ctx.effect(() => ctx.inputTriggers.registerSource(promptSource), 'local-docs: @ prompt source')

  ctx.slots.inject('sidebar.panellist', () =>
    ctx.slots.register({
      name: 'sidebar.panellist',
      id: PANEL_ID,
      order: 10,
      label: () => t('panel'),
      locale: NS,
    }, SidebarIcon),
  )
}
