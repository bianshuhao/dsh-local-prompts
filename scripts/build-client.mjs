import { createRequire } from 'node:module'
import { readFile, writeFile, unlink } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const here = resolve(import.meta.dirname, '..')
const nodeModules = resolve(here, 'node_modules')
const require = createRequire(import.meta.url)
const esbuildPath = require.resolve('esbuild')
const { build } = await import(pathToFileURL(esbuildPath).href)

const outfile = resolve(here, '.client.bundle.cjs')
await build({
  absWorkingDir: here,
  entryPoints: [resolve(here, 'src/client/index.tsx')],
  outfile,
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react'],
  nodePaths: [nodeModules],
  alias: { 'react/jsx-runtime': resolve(here, 'src/client/jsx-runtime.ts') },
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  logLevel: 'info',
})

const code = await readFile(outfile, 'utf8')
const pkg = JSON.parse(await readFile(resolve(here, 'package.json'), 'utf8'))
const wrapped = `/* Generated by scripts/build-client.mjs. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function(module, exports, require) {
${code}
    }).call(undefined, module, exports, require);
    return module.exports;
  },
});
`
await writeFile(resolve(here, 'client.js'), wrapped, 'utf8')
await unlink(outfile)
console.log(`wrote client.js (${(wrapped.length / 1024).toFixed(1)} KiB)`)
